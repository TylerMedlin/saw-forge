// Packs every app in apps.json into a reproducible zip and writes the catalog
// the hub reads (with each package's SHA-256), into dist-apps/:
//   dist-apps/<id>-<version>.zip, dist-apps/icons/<id>.png, dist-apps/catalog.json
// The same sources always produce byte-identical packages (sorted entries,
// fixed timestamps), so anyone can rebuild a release and compare checksums.
// Also writes build/installer.nsh so the Windows uninstaller can remove
// the shortcuts the hub creates for these apps.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { writeZip } = require('../main/zip.js');
const DESKTOP = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(DESKTOP, 'dist-apps');
const cfg = JSON.parse(readFileSync(join(DESKTOP, 'sawforge.config.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(DESKTOP, 'package.json'), 'utf8'));
const { apps, comingSoon } = JSON.parse(readFileSync(join(DESKTOP, 'apps.json'), 'utf8'));
const SKIP = /(^|[\\/])(\.git|node_modules|saves|exports|\.DS_Store|Thumbs\.db)([\\/]|$)/;

function walk(dir, base, out) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (SKIP.test(full)) continue;
    const st = statSync(full);
    if (st.isDirectory()) walk(full, base, out);
    else out.push({ name: relative(base, full).split(sep).join('/'), data: readFileSync(full) });
  }
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'icons'), { recursive: true });
const tag = `v${pkg.version}`;
const catalog = { schema: 1, hub: pkg.version, apps: [], comingSoon: comingSoon || [] };
const nshApps = [];

for (const a of apps) {
  const root = join(DESKTOP, a.root), files = [];
  for (const inc of a.include) {
    const p = join(root, inc);
    if (!existsSync(p)) throw new Error(`${a.id}: missing ${inc}`);
    if (statSync(p).isDirectory()) walk(p, root, files); else files.push({ name: inc, data: readFileSync(p) });
  }
  const manifest = { id: a.id, name: a.name, version: a.version, tagline: a.tagline, entry: 'index.html', window: a.window, dataFolder: a.dataFolder || a.name, license: 'GPL-3.0-or-later', publisher: cfg.publisher };
  files.push({ name: '.sawforge/app.json', data: Buffer.from(JSON.stringify(manifest, null, 2)) });
  files.push({ name: '.sawforge/icon.png', data: readFileSync(join(DESKTOP, a.icon)) });
  if (a.iconIco) files.push({ name: '.sawforge/icon.ico', data: readFileSync(join(DESKTOP, a.iconIco)) });
  const zip = writeZip(files), file = `${a.id}-${a.version}.zip`;
  writeFileSync(join(OUT, file), zip);
  writeFileSync(join(OUT, 'icons', `${a.id}.png`), readFileSync(join(DESKTOP, a.icon)));
  const sha256 = createHash('sha256').update(zip).digest('hex');
  catalog.apps.push({
    id: a.id, name: a.name, version: a.version, tagline: a.tagline, description: a.description, category: a.category, notes: a.notes, dataFolder: a.dataFolder || a.name,
    file, size: zip.length, sha256, url: `https://github.com/${cfg.githubOwner}/${cfg.githubRepo}/releases/download/${tag}/${file}`,
  });
  nshApps.push(`    Delete "$SMPROGRAMS\\Saw Forge\\${a.name}.lnk"`, `    Delete "$DESKTOP\\${a.name}.lnk"`);
  console.log(`${file}  ${files.length} files  ${(zip.length / 1024).toFixed(0)} KB  sha256 ${sha256}`);
}
writeFileSync(join(OUT, 'catalog.json'), JSON.stringify(catalog, null, 2));
// What the Windows uninstaller removes besides the hub itself: the apps it
// installed and their shortcuts. Projects in Documents\Saw Forge are kept.
// Skipped when the uninstaller runs as part of an update.
const nsh = [
  '; Generated by scripts/pack-apps.mjs from apps.json. Do not edit by hand.',
  '!macro customUnInstall',
  '  ${ifNot} ${isUpdated}',
  '    RMDir /r "$LOCALAPPDATA\\Saw Forge Hub\\apps"',
  '    RMDir "$LOCALAPPDATA\\Saw Forge Hub"',
  '    SetShellVarContext current',
  ...nshApps,
  '    RMDir "$SMPROGRAMS\\Saw Forge"',
  '    ${if} $installMode == "all"',
  '      SetShellVarContext all',
  '    ${endIf}',
  '  ${endIf}',
  '!macroend',
];
writeFileSync(join(DESKTOP, 'build', 'installer.nsh'), nsh.join('\r\n') + '\r\n');
console.log(`catalog.json: ${catalog.apps.length} app(s) for hub ${pkg.version}`);
